// v0.10.2: link schemes, whitespace tidy-up, and long-reply clipping.
import { test } from "node:test";
import assert from "node:assert";
import { execSync } from "node:child_process";
execSync("npx -y esbuild@0.24.0 test/safety-entry.ts --bundle --platform=node --format=esm --outfile=node_modules/.cache/hm-safety/s.js --log-level=error");
const { safeHref, tidyText, clipLong, newReplies, parseWatch, isGatewayNotice, parseNotice, decodeEscapes, tidyEscapes, fileKind, withFiles, splitFiles, FILE_TEXT_LIMIT } = await import("../node_modules/.cache/hm-safety/s.js");

test("only http(s), mailto and tel links open", () => {
  assert.equal(safeHref("https://x.com/a"), "https://x.com/a");
  assert.equal(safeHref("mailto:a@b.c"), "mailto:a@b.c");
  assert.equal(safeHref("www.example.com"), "https://www.example.com");
  for (const bad of ["javascript:alert(1)", " JavaScript:alert(1)", "intent://scan#Intent;end", "file:///data/data/x", "content://x", "hermes://bot/x", "data:text/html,hi"]) assert.equal(safeHref(bad), undefined, bad);
});

test("a reply that is mostly blank lines can't make a giant empty bubble", () => {
  assert.equal(tidyText("Hi\n\n\n\n\n\nthere   \n\n\n"), "Hi\n\nthere");
  assert.equal(tidyText("\n".repeat(5000)), "");
});

test("huge replies render clipped at a paragraph with the rest on demand", () => {
  const para = "x".repeat(1000);
  const long = Array(12).fill(para).join("\n\n");
  const c = clipLong(long);
  assert.ok(c.clipped && c.text.length <= 6000 && c.text.endsWith("x"));
  assert.deepEqual(clipLong("short"), { text: "short", clipped: false });
});

test("background check: only assistant replies after the mark count", () => {
  const h = [
    { role: "user", text: "hi", at: 2000 }, { role: "assistant", text: "old", at: 1000 },
    { role: "assistant", text: "new", at: 3000 }, { role: "assistant", text: "   ", at: 4000 }, { role: "assistant", text: "no time" },
  ];
  assert.deepEqual(newReplies(h, 1500).map((m) => m.text), ["new"]);
  assert.equal(parseWatch("garbage"), null);
  assert.deepEqual(parseWatch(JSON.stringify({ since: 5, chats: [{ botId: "a", sid: "s" }, { botId: 1 }] })), { since: 5, chats: [{ botId: "a", sid: "s" }] });
});

// The message from Surya's screenshot: a relay delivery dump + the gateway's footer, stored as role=user.
const FOOTER = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]";
const NOTICE = `[SYSTEM: Ledger delivered a routine update]\n[\n  {"from": "ledger", "message": "So the cron pipeline is fully healthy again \\u2014 all three jobs are on a working model.\\n\\nStanding HDFC \\u20b911,047 payment due Tuesday.", "status": "settled", "delivery_id": "ae87f492b26d3a57e589851c10f3611e"}\n]\n\n${FOOTER}`;

test("gateway notices are recognised and turned into a title + readable body", () => {
  assert.ok(isGatewayNotice(NOTICE));
  assert.ok(!isGatewayNotice("What's my HDFC balance?"));
  const n = parseNotice(NOTICE);
  assert.equal(n.title, "Ledger delivered a routine update");
  assert.match(n.body, /fully healthy again — all three jobs/);
  assert.match(n.body, /₹11,047/);
  assert.ok(!/delivery_id|\\u|INTERNAL NOTIFICATION/.test(n.body), n.body);
});

test("a notice without JSON or a header still gets a sensible chip", () => {
  const n = parseNotice(`Process 4411 finished: exit 0\\nall good\n\n${FOOTER}`);
  assert.equal(n.title, "Process 4411 finished: exit 0");
  assert.match(n.body, /exit 0\nall good/);
  assert.match(parseNotice(`[{"status":"settled","delivery_id":"x"}]\n\n${FOOTER}`).title, /^Background update/);
});

test("escapes: decoded when text clearly arrived double-encoded, code fences left alone", () => {
  assert.equal(decodeEscapes("a\\nb \\u2014 c \\\"q\\\""), 'a\nb — c "q"');
  assert.equal(tidyEscapes("Pay \\u20b9500 today"), "Pay ₹500 today");
  assert.equal(tidyEscapes("Line one\\n\\nLine two\\nthree"), "Line one\n\nLine two\nthree");
  assert.equal(tidyEscapes("Use printf(\"a\\n\") here\nand there"), "Use printf(\"a\\n\") here\nand there"); // one literal \n, real lines: untouched
  assert.equal(decodeEscapes("```\nconsole.log(\"\\u2014\\n\")\n```"), "```\nconsole.log(\"\\u2014\\n\")\n```");
});

test("files: kinds, inline blocks within Hermes's limit, and round trip from history", () => {
  assert.equal(fileKind("notes.md"), "text");
  assert.equal(fileKind("data", "application/json"), "text");
  assert.equal(fileKind("scan.PNG"), "image");
  assert.equal(fileKind("report.pdf", "application/pdf"), "unsupported");
  const msg = withFiles("Summarise these", [{ name: "a.csv", text: "x,y\n1,2" }, { name: "b.txt", text: "hello" }]);
  assert.match(msg, /^Summarise these\n\n<attached-file name="a.csv">\nx,y\n1,2\n<\/attached-file>/);
  assert.deepEqual(splitFiles(msg), { text: "Summarise these", files: ["a.csv", "b.txt"] });
  assert.deepEqual(splitFiles("plain"), { text: "plain", files: [] });
  const big = withFiles("", [{ name: "big.log", text: "z".repeat(FILE_TEXT_LIMIT + 500) }]);
  assert.ok(big.length < FILE_TEXT_LIMIT + 300 && /cut/.test(big));
});
